// ---------- Helpers ----------
const UK_TRANSLIT = {
  а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', є: ['ye', 'ie'], ж: 'zh', з: 'z', и: 'y',
  і: 'i', ї: ['yi', 'i'], й: ['y', 'i'], к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch', ь: '', ю: ['yu', 'iu'],
  я: ['ya', 'ia'], ы: 'y', э: 'e', ё: 'yo', ъ: '', "'": '', '’': '', 'ʼ': ''
};

// Ukrainian national transliteration (KMU 2010): є/ї/й/ю/я differ at the start of a word; "зг" -> "zgh".
function slugify(text) {
  const s = text.toLowerCase();
  let out = '';
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    const m = UK_TRANSLIT[ch];
    if (m === undefined) { out += ch; continue; }
    if (Array.isArray(m)) {
      const wordStart = i === 0 || !/[a-zа-яіїєґ'’ʼ]/.test(s[i - 1]);
      out += wordStart ? m[0] : m[1];
    } else if (ch === 'г' && s[i - 1] === 'з') {
      out += 'gh';
    } else {
      out += m;
    }
  }
  return out.normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const hasCyrillic = s => /[а-яіїєґё]/i.test(s);

// East Slavic plural forms (uk and ru share the rule).
function slavicPlural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
}
const enPlural = (n, one, many) => (n === 1 ? one : many);

function joinWith(names, and) {
  if (names.length <= 1) return names.join('');
  return names.slice(0, -1).join(', ') + and + names[names.length - 1];
}

function git(args) {
  try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); }
  catch { return ''; }
}
const TODAY = new Date().toISOString().slice(0, 10);
function lastmodFor(files) {
  if (process.env.SITEMAP_LASTMOD) return process.env.SITEMAP_LASTMOD;
  const dirty = git(['status', '--porcelain', '--', ...files]);
  if (dirty) return TODAY;
  return git(['log', '-1', '--format=%cs', '--', ...files]) || TODAY;
}

